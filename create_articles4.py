def create_article(article):
    slug = article["slug"]
    folder = os.path.join(BASE_DIR, slug)
    os.makedirs(folder, exist_ok=True)

    tags_str = "\n".join([f'  - "{t}"' for t in article["tags"]])

    body = article["body"]
    if article.get("add_bgm"):
        body = body.rstrip() + "\n" + BGM_SECTION

    content = f"""+++
title = "{article['title']}"
date = "{article['date']}"
description = "{article['description']}"
tags = [
{tags_str}
]
[cover]
  image = "cover.png"
  alt = "{article['title']}"
+++

{body.strip()}
"""

    index_path = os.path.join(folder, "index.md")
    with open(index_path, "w", encoding="utf-8") as f:
        f.write(content)

    cover_path = os.path.join(folder, "cover.png")
    if not os.path.exists(cover_path) and os.path.exists(PLACEHOLDER_COVER):
        shutil.copy(PLACEHOLDER_COVER, cover_path)

    print(f"OK: {slug}")


